using System.Diagnostics;
using System.Linq;

var numbers = Enumerable.Range(1, 5_000_000);

// LINQ
Stopwatch sw = Stopwatch.StartNew();

var result1 = numbers
    .Select(x => x * 2)
    .ToList();

sw.Stop();
long linqTime = sw.ElapsedMilliseconds;

// PLINQ
sw.Restart();

var result2 = numbers
    .AsParallel()
    .Select(x => x * 2)
    .ToList();

sw.Stop();
long plinqTime = sw.ElapsedMilliseconds;

Console.WriteLine($"LINQ time: {linqTime} ms");
Console.WriteLine($"PLINQ time: {plinqTime} ms");

Console.WriteLine($"Speedup: {(double)linqTime / plinqTime:F2}x");

/*В первом тесте выполняются тяжёлые математические вычисления. 
PLINQ распределяет работу между несколькими потоками и ядрами процессора, 
благодаря чему вычисления могут выполняться быстрее

Во втором тесте операция x * 2 очень простая и занимает мало времени. 
Создание и координация потоков, распределение работы и объединение результатов требуют дополнительных ресурсов. 
Эти расходы могут оказаться больше, чем выигрыш от параллельной обработки
*/


/*
PLINQ может ускорить программу, когда нужно обработать
большое количество элементов и для каждого элемента
выполняются сложные вычисления

PLINQ бессмысленно использовать, когда операции очень простые,
например умножение числа на 2. В таком случае расходы
на параллельную обработку могут быть больше чем польза

Большая коллекция сама по себе не гарантирует ускорение.
Важно учитывать сложность операций, количество ядер процессора
и расходы на распределение и объединение результатов

CPU-bound операции являются хорошим кандидатом для PLINQ,
потому что они нагружают процессор. Несколько ядер могут
выполнять вычисления одновременно

AsOrdered() сохраняет исходный порядок элементов в результате.
Но для этого требуется дополнительная координация и ресурсы, которые
могут снизить производительность

WithDegreeOfParallelism() позволяет указать максимальное
количество параллельных задач, используемых PLINQ.
Это помогает контролировать нагрузку на процессор.
Слишком маленькое или слишком большое значение может
ухудшить производительность
*/
